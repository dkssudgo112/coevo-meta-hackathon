import { useState } from 'react';
import type { PracticeAttempt, Snapshot } from '../../../../packages/contracts/index.ts';
import { INGREDIENT_KEYS } from '../../../../packages/contracts/index.ts';
import { post, postBinary, type Creds } from '../lib/api.ts';
import { AssistLabel, errorText, INGREDIENT_TEXT, MediaImage } from '../ui/common.tsx';
import { VoiceButton } from './Voice.tsx';

export function PracticeRange({ creds, state, attemptId, onStart }: { creds: Creds; state: Snapshot; attemptId: string | null; onStart: (id: string) => void }) {
  const p: PracticeAttempt | undefined = attemptId ? state.practice.find(x => x.id === attemptId) : undefined;
  const [err, setErr] = useState('');
  const [confirmHint, setConfirmHint] = useState(false);

  const start = async () => {
    setErr('');
    try { onStart((await post<PracticeAttempt>(creds, '/practice', { autoOpened: false })).id); } catch (e) { setErr(errorText(e)); }
  };

  if (!p) {
    return (
      <div className="stack">
        <p className="muted">A 30-second drill: a new request arrives, you brief the AI out loud, and Muse Image draws what your words produce.</p>
        <button className="btn primary" onClick={start}>Give me a request</button>
        {err && <p className="faint" role="alert">{err}</p>}
      </div>
    );
  }
  if (p.status === 'scenario') return <p className="faint" role="status">Writing a practice request…</p>;
  if (p.status === 'failed' && !p.scenario) return <div className="notice warn" role="alert">{p.error} <button className="btn small" onClick={start}>Try again</button></div>;

  return (
    <div className="stack">
      <div className="card stack">
        <div className="eyebrow">Practice request</div>
        <p style={{ fontFamily: 'var(--serif)', fontSize: '1.25rem' }}>{p.scenario}</p>
        {p.hintViewed ? <p className="faint">Hint: {p.hint}</p> : confirmHint ? (
          <div className="notice">Seeing the hint marks this attempt as “With the Caddie”. <button className="btn small" onClick={() => post(creds, `/practice/${p.id}/hint`)}>Show hint</button> <button className="btn ghost small" onClick={() => setConfirmHint(false)}>Keep going without it</button></div>
        ) : p.status === 'open' && <button className="linklike" onClick={() => setConfirmHint(true)}>Hint</button>}
      </div>
      {(p.status === 'open' || p.status === 'failed') && (
        <>
          <VoiceButton label="Brief the AI out loud" maxSeconds={45} onWav={wav => postBinary(creds, `/practice/${p.id}/attempt`, wav, 'audio/wav')} />
          {p.status === 'failed' && <p className="faint" role="alert">{p.error}</p>}
        </>
      )}
      {p.status === 'transcribing' && <p className="faint" role="status">Transcribing your brief…</p>}
      {p.status === 'checking' && <p className="faint" role="status">Drawing it with Muse Image and checking the ingredients…</p>}
      {p.transcript && <p><span className="faint">You said:</span> <span className="quote">{p.transcript}</span></p>}
      {p.status === 'done' && (
        <div className="stack">
          {p.imageStatus === 'ready' ? <MediaImage creds={creds} k={p.imageKey} alt="Poster generated by Muse Image from your spoken brief" className="poster-img" /> : <div className="notice">The image could not be drawn. The ingredient check still counts.</div>}
          <ul className="stack" style={{ listStyle: 'none', padding: 0, gap: 4 }}>
            {INGREDIENT_KEYS.map(k => <li key={k}>{p.ingredients?.[k] ? '✓' : '○'} {INGREDIENT_TEXT[k]}</li>)}
          </ul>
          <p>{p.checkNote}</p>
          <div className="row">{p.assistance && <AssistLabel value={p.assistance} extra="practice" />}{p.autoOpened && <span className="faint">Opened by the Caddie</span>}</div>
          <button className="btn" onClick={start}>Another request</button>
        </div>
      )}
    </div>
  );
}
