// Build metadata for streaming media ranges. The asset binding may omit Content-Length.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const publicDir = path.join(root, 'apps/web/public');
const lengths = {};
function visit(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) visit(full);
    else if (/\.(mp4|m4a)$/.test(e.name)) lengths['/' + path.relative(publicDir, full).split(path.sep).join('/')] = statSync(full).size;
  }
}
visit(publicDir);
writeFileSync(path.join(root, 'apps/api/src/media-sizes.ts'), '// Generated by scripts/media-sizes.mjs from the published media files.\nexport const STATIC_MEDIA_LENGTHS: Readonly<Record<string, number>> = ' + JSON.stringify(lengths, null, 2) + ';\n');
console.log(`Recorded lengths for ${Object.keys(lengths).length} public media files.`);
